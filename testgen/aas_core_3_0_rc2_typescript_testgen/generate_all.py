"""Generate all the code using testgen."""

import os
import pathlib
import re
import shlex
import subprocess
import sys

# NOTE (aaronzi, 2026-11-05):
# The generators do not emit any copyright or license information, so we
# prepend the header to the generated test files ourselves. Otherwise, the headers
# would be lost on every re-generation.
#
# REUSE-IgnoreStart
_LICENSE_HEADER = """\
// SPDX-FileCopyrightText: 2022 aas-core3.0rc02-typescript AUTHORS
//
// SPDX-License-Identifier: MIT

"""
# REUSE-IgnoreEnd

_LEADING_SPDX_COMMENTS_RE = re.compile(r"\A(?://\s*(?:SPDX-[A-Za-z-]+:.*)?\n|\n)*")

_GENERATED_MARKER = "// This code has been automatically generated by:"


def _prepend_license_header(text: str) -> str:
    """Replace any leading SPDX comment block in ``text`` with our license header."""
    return _LICENSE_HEADER + _LEADING_SPDX_COMMENTS_RE.sub("", text, count=1)


def _add_license_headers(test_dir: pathlib.Path) -> None:
    """Prepend the license header to all the test files generated by testgen."""
    for path in sorted(test_dir.glob("*.ts")):
        text = path.read_text(encoding="utf-8")
        if _GENERATED_MARKER not in text:
            continue

        path.write_text(_prepend_license_header(text), encoding="utf-8")


def main() -> int:
    """Execute the main routine."""
    this_path = pathlib.Path(os.path.realpath(__file__))
    testgen_dir = this_path.parent

    for script_pth in sorted(testgen_dir.glob("generate_*.py")):
        if script_pth == this_path:
            continue

        cmd = [
            sys.executable,
            str(script_pth)
        ]

        cmd_str = " ".join(shlex.quote(part) for part in cmd)

        print(f"Executing: {script_pth.relative_to(testgen_dir)}")
        return_code = subprocess.call(cmd, cwd=str(script_pth.parent))
        if return_code != 0:

            print(
                f"Failed with return code {return_code}: {cmd_str}",
                file=sys.stderr
            )
            return 1

    repo_root = testgen_dir.parent.parent
    _add_license_headers(repo_root / "test")

    return 0


if __name__ == "__main__":
    sys.exit(main())
